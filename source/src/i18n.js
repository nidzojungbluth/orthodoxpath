/* Serbisch: Kyrillisch -> Lateinisch (eindeutig, verlustfrei) */
const CYR2LAT = {
  "а":"a","б":"b","в":"v","г":"g","д":"d","ђ":"đ","е":"e","ж":"ž","з":"z","и":"i","ј":"j","к":"k",
  "л":"l","љ":"lj","м":"m","н":"n","њ":"nj","о":"o","п":"p","р":"r","с":"s","т":"t","ћ":"ć","у":"u",
  "ф":"f","х":"h","ц":"c","ч":"č","џ":"dž","ш":"š"
};
function translit(text) {
  if (!text) return text;
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const lower = ch.toLowerCase();
    const m = CYR2LAT[lower];
    if (m === undefined) { out += ch; continue; }
    if (ch === lower) { out += m; continue; }
    // Großbuchstabe: bei Digraphen hängt die Schreibweise vom Folgezeichen ab (ЉУБАВ -> LJUBAV, Љубав -> Ljubav)
    if (m.length > 1) {
      const next = text[i + 1] || "";
      const nextIsUpper = next && next !== next.toLowerCase();
      out += nextIsUpper ? m.toUpperCase() : m[0].toUpperCase() + m.slice(1);
    } else out += m.toUpperCase();
  }
  return out;
}

